// --- run ---------------------------------------------------------------------------------------------------------

if (rehearse) mkdirSync(rehearse, { recursive: true })
const db = await seed(opt('pg'))
writeProject(project, db.url)
console.log(`coffee_shop seeded: ${db.orders} orders, newest ${db.newest}, ${db.unshipped} not shipped yet`)
console.log(`project folder: ${project}${existsSync(join(project, '.env')) ? ' (with .env)' : ''}`)
const ctx = await session({ ...WINDOW, scale: rehearse ? 2 : 0, theme: 'light', background: !!(argv.includes('--background') || rehearse), realHome: ai === 'claude-code' || ai === 'codex' })
try {
  await SCENE[scene].setup(ctx)
  await ctx.win.waitForTimeout(800)
  await still(ctx.win, 'start')
  if (rehearse) {
    t0 = Date.now()
    await SCENE[scene].act(ctx)
    await park(ctx.win)
    await still(ctx.win, 'end')
    writeFileSync(join(rehearse, `scene-${scene}-timings.txt`), `${timings.join('\n')}\n`)
  } else {
    console.log(`Scene ${scene} is ready. Record, then close the app window (or press Ctrl+C here) to end.`)
    await new Promise((done) => {
      ctx.app.on('close', done)
      process.on('SIGINT', done)
    })
  }
} catch (err) {
  console.error(`Scene ${scene} failed: ${err.message.split('\n')[0]}`)
  if (rehearse) await ctx.win.screenshot({ path: join(rehearse, `scene-${scene}-failed.png`) }).catch(() => {})
  process.exitCode = 1
} finally {
  await ctx.close()
}

