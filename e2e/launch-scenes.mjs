/** The connections of the project's .env, as Import connections → From a project folder… brings them in. */
async function importProject(ctx) {
  await ctx.app.evaluate(({ dialog }, path) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] })
  }, project)
  await ctx.win.getByRole('button', { name: 'Import connections' }).first().click()
  await ctx.win.getByRole('menuitem', { name: /From a project folder/ }).click()
  await ctx.win.getByText(/coffee-shop — DATABASE_URL/).first().waitFor({ timeout: 15000 })
  await quietToasts(ctx.win)
}

async function connect({ win }) {
  await win.getByText(/coffee-shop — DATABASE_URL/).first().click()
  await win.getByPlaceholder(/Filter \d+ tables/).waitFor({ timeout: 20000 })
  await win.waitForTimeout(600)
}

async function diagram({ win }) {
  await palette(win, 'ER diagram')
  await win.locator('.react-flow__node').first().waitFor({ timeout: 15000 })
  await win.getByRole('button', { name: 'Auto layout' }).click()
  await win.waitForTimeout(1200)
}

/** The diagram fitted to its pane, with no focus ring left on the button. */
async function fitDiagram(win) {
  await win.locator('.react-flow__controls-fitview:visible').click()
  await win.evaluate(() => document.activeElement?.blur())
  await win.waitForTimeout(400)
}

