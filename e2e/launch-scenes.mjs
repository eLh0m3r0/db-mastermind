const ENGLISH = [
  [/'Praha'/g, "'Prague'"],
  [/'Wien'/g, "'Vienna'"],
  [/'Plzeň'/g, "'Pilsen'"],
  [/'Kraków'/g, "'Krakow'"],
  [/'Hand Grinder Comandante'/g, "'Hand Grinder'"],
  [/'V60 Dripper'/g, "'Pour-over Dripper'"],
  [/'AeroPress'/g, "'Travel Press'"],
  [/'Gift Voucher 1000 CZK'/g, "'Gift Voucher'"],
]
const AFTER = [
  // Dates relative to today: the last shipment was yesterday, everything else moves with it.
  `do $$ declare d integer; begin
     select (current_date - 1) - greatest(max(ordered_at), max(shipped_at)) into d from orders;
     update orders set ordered_at = ordered_at + d, shipped_at = shipped_at + d;
     update payments set paid_at = paid_at + d;
     update customers set created_at = created_at + d;
   end $$`,
  'alter table products alter column active drop default, alter column active type boolean using active = 1, alter column active set default true',
  'alter table customers alter column newsletter drop default, alter column newsletter type boolean using newsletter = 1, alter column newsletter set default false',
  ...['categories', 'products', 'customers', 'employees', 'orders', 'payments'].map((t) => `select setval(pg_get_serial_sequence('${t}', 'id'), (select max(id) from ${t}))`),
  'create index ix_orders_customer on orders (customer_id)',
  'create index ix_orders_status_date on orders (status, ordered_at)',
  'create index ix_products_category on products (category_id)',
  `create view customer_revenue as
   select c.id, c.first_name || ' ' || c.last_name as customer, c.country,
          count(distinct o.id) as orders, round(sum(i.quantity * i.unit_price), 2) as revenue
     from customers c
     join orders o on o.customer_id = c.id and o.status <> 'cancelled'
     join order_items i on i.order_id = o.id
    group by c.id`,
  "comment on table orders is 'One row per order; status goes new → paid → shipped, or cancelled'",
]

async function seed(url) {
  const pg = createRequire(join(repo, 'package.json'))('pg')
  const admin = new pg.Client({ connectionString: url })
  await admin.connect()
  await admin.query("select pg_terminate_backend(pid) from pg_stat_activity where datname = 'coffee_shop' and pid <> pg_backend_pid()")
  await admin.query('drop database if exists coffee_shop')
  await admin.query('create database coffee_shop')
  await admin.end()
  const target = new URL(url)
  target.pathname = '/coffee_shop'
  const db = new pg.Client({ connectionString: target.toString() })
  await db.connect()
  await db.query('begin')
  for (const sql of DDL) await db.query(sql)
  await db.query("insert into employees values (1, 'Alice Morgan', 'Head of Sales', null), (2, 'Ben Carter', 'Sales', 1), (3, 'Chloe Evans', 'Sales', 1), (4, 'Daniel Hughes', 'Support', 1)")
  for (const sql of sampleDatabaseSql().filter((s) => s.startsWith('INSERT INTO') && !s.startsWith('INSERT INTO employees'))) {
    await db.query(ENGLISH.reduce((s, [from, to]) => s.replace(from, to), sql))
  }
  for (const sql of AFTER) await db.query(sql)
  await db.query('commit')
  const { rows } = await db.query("select count(*)::int as orders, max(ordered_at)::text as newest, count(*) filter (where shipped_at is null)::int as unshipped from orders")
  await db.end()
  return { url: target.toString(), ...rows[0] }
}

/** The project folder whose .env the hook scene drops on the window. */
function writeProject(dir, url) {
  mkdirSync(join(dir, 'src'), { recursive: true })
  writeFileSync(join(dir, '.env'), `# Coffee shop API, local development\nPORT=3000\nDATABASE_URL="${url}"\n`)
  writeFileSync(join(dir, 'package.json'), `${JSON.stringify({ name: 'coffee-shop', private: true, scripts: { dev: 'node src/server.js' } }, null, 2)}\n`)
  writeFileSync(join(dir, 'src', 'server.js'), "// The shop's API (a placeholder for the video).\n")
  writeFileSync(join(dir, 'README.md'), '# Coffee shop\n\nThe online shop of a small coffee roaster.\n')
}

