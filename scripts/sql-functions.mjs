#!/usr/bin/env node
// Regenerates packages/core/src/functions/*-catalog.ts, the editor's function completions, from the engines' own catalogs:
// PostgreSQL's pg_catalog (a running container: npm run db:up), DuckDB's duckdb_functions() and SQLite's
// pragma_function_list (node:sqlite, the same SQLite the app runs).
// Usage: node scripts/sql-functions.mjs [container]   (default db-mastermind-postgres-1)
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { DatabaseSync } from 'node:sqlite'
import { DuckDBInstance } from '@duckdb/node-api'

const container = process.argv[2] ?? 'db-mastermind-postgres-1'

// Machinery the planner, aggregates, upgrades and statistics views call; nobody types these.
const NOISE = [
  /^binary_upgrade_/, /(larger|smaller)$/, /_accum(_inv)?$/, /_statefunc$/, /_transfn$/, /_combine$/, /_subdiff$/, /_canonical$/,
  /^(float[48]|int[248]|int2int4|numeric|interval)_/, /^int[248](inc|dec)/, /^pg_stat_get_/, /_validator$/, /^fmgr_/,
  /^spg_/, /^d(exp|log1|log10|round|trunc)$/, /^(currtid2|nameconcatoid|amvalidate|aclinsert|aclremove|aclcontains|makeaclitem|xmlconcat2|textlen|like|notlike|pg_nextoid|pg_stop_making_pinned_objects|pg_isolation_test_session_is_blocked|cashlarger|cashsmaller|cash_words|querytree|pclose|popen|bound_box|in_range|multirange_intersect_agg_transfn|range_intersect_agg_transfn|pg_get_wal_resource_managers)$/,
]

const query = `
SELECT coalesce(json_agg(f ORDER BY f.name, f.args), '[]') FROM (
  SELECT p.proname AS name, p.prokind::text AS kind,
         pg_get_function_arguments(p.oid) AS args, pg_get_function_result(p.oid) AS result, d.description AS doc
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    LEFT JOIN pg_description d ON d.objoid = p.oid AND d.classoid = 'pg_proc'::regclass AND d.objsubid = 0
   WHERE n.nspname = 'pg_catalog' AND p.proname !~ '^_'
     AND p.prorettype NOT IN ('internal'::regtype, 'cstring'::regtype, 'trigger'::regtype, 'event_trigger'::regtype,
                              'language_handler'::regtype, 'fdw_handler'::regtype, 'index_am_handler'::regtype,
                              'table_am_handler'::regtype, 'tsm_handler'::regtype)
     AND NOT ('internal'::regtype = ANY (p.proargtypes::oid[]) OR 'cstring'::regtype = ANY (p.proargtypes::oid[]))
     AND coalesce(d.description, '') !~* '^(implementation of|I/O|planner support|less-equal-greater|hash|sort support|internal|deprecated|btree|gist|gin|spgist|brin|join selectivity|restriction selectivity|equal image|in_range)'
     AND p.proname NOT IN (SELECT typname FROM pg_type)
) f`

const version = execFileSync('docker', ['exec', container, 'psql', '-U', 'postgres', '-Atc', 'SHOW server_version'], { encoding: 'utf8' }).trim()
const rows = JSON.parse(execFileSync('docker', ['exec', '-i', container, 'psql', '-U', 'postgres', '-At'], { input: query, encoding: 'utf8', maxBuffer: 64 << 20 }))

const byName = new Map()
for (const r of rows) {
  if (NOISE.some((re) => re.test(r.name))) continue
  const e = byName.get(r.name) ?? { kind: r.kind, signatures: [], doc: '', docRank: -1 }
  // Aggregate/window beats plain: count(*) is an aggregate even though no overload says so twice.
  if (r.kind === 'a' || r.kind === 'w') e.kind = r.kind
  const sig = `(${r.args})${r.result ? ` → ${r.result}` : ''}`
  if (!e.signatures.includes(sig)) e.signatures.push(sig)
  // The description of the overload people use most (text, timestamptz) rather than the first one (bytea, interval).
  const rank = !r.doc ? -1 : /\b(bytea|interval|bit|money|macaddr8?|xid8?|pg_lsn|tid|oid)\b/.test(r.args) ? 0 : /\b(text|timestamp with time zone|jsonb)\b/.test(r.args) ? 2 : 1
  if (rank > e.docRank) Object.assign(e, { doc: r.doc, docRank: rank })
  byName.set(r.name, e)
}


function write(file, constName, source, entries) {
  const lines = entries.map(([name, e]) => `  [${JSON.stringify(name)}, '${e.kind}', ${JSON.stringify(e.signatures.slice(0, 6))}, ${JSON.stringify(e.doc ?? '')}],`)
  const out = `// Generated by scripts/sql-functions.mjs from ${source}; do not edit by hand.
// [name, kind (f function, a aggregate, w window), signatures, description]
export const ${constName}: ReadonlyArray<readonly [string, 'f' | 'a' | 'w', readonly string[], string]> = [
${lines.join('\n')}
]
`
  const target = fileURLToPath(new URL(`../packages/core/src/functions/${file}`, import.meta.url))
  writeFileSync(target, out)
  console.log(`${entries.length} functions from ${source} → ${target}`)
}

const pgKind = { f: 'f', a: 'a', w: 'w', p: 'f' }
write('postgres-catalog.ts', 'POSTGRES_CATALOG', `PostgreSQL ${version}'s pg_catalog`, [...byName.entries()].map(([n, e]) => [n, { ...e, kind: pgKind[e.kind] ?? 'f' }]))

// DuckDB: scalar, aggregate and table functions; operators and internal helpers (__x, symbols) are left out.
{
  const db = await DuckDBInstance.create(':memory:')
  const c = await db.connect()
  const version = (await c.runAndReadAll('SELECT version()')).getRows()[0][0]
  const rows = (
    await c.runAndReadAll(`SELECT function_name AS name, function_type AS type, parameters AS params, parameter_types AS types,
                                  return_type AS result, description AS doc
                             FROM duckdb_functions()
                            WHERE function_type IN ('scalar', 'aggregate', 'table', 'table_macro', 'macro')
                              AND regexp_matches(function_name, '^[a-z][a-z0-9_]*$')
                            ORDER BY function_name`)
  ).getRowObjectsJson()
  const map = new Map()
  for (const r of rows) {
    const e = map.get(r.name) ?? { kind: r.type === 'aggregate' ? 'a' : 'f', signatures: [], doc: '' }
    const params = (r.params ?? []).map((p, i) => (r.types?.[i] && r.types[i] !== 'ANY' ? `${p} ${r.types[i]}` : p))
    // Table functions (read_csv) take dozens of named options in no stable order: show the first argument only.
    const shown = r.type.startsWith('table') && params.length > 2 ? [params[0], '…'] : params.length > 6 ? [...params.slice(0, 6), '…'] : params
    const sig = `(${shown.join(', ')})${r.result ? ` → ${r.result}` : ''}`
    if (!e.signatures.includes(sig)) e.signatures.push(sig)
    if (!e.doc && r.doc) e.doc = r.doc
    map.set(r.name, e)
  }
  write('duckdb-catalog.ts', 'DUCKDB_CATALOG', `DuckDB ${version}'s duckdb_functions()`, [...map.entries()])
}

// SQLite reports names and argument counts only.
{
  const db = new DatabaseSync(':memory:')
  const version = db.prepare('SELECT sqlite_version() AS v').get().v
  const rows = db.prepare(`SELECT name, narg, type FROM pragma_function_list WHERE builtin = 1 AND name GLOB '[a-z]*'
                              AND name NOT IN ('likelihood', 'likely', 'unlikely', 'sqlite_log', 'load_extension') ORDER BY name, narg`).all()
  const map = new Map()
  for (const r of rows) {
    const e = map.get(r.name) ?? { kind: r.type === 'a' ? 'a' : r.type === 'w' ? 'w' : 'f', signatures: [], doc: '' }
    if (r.type === 'w') e.kind = 'w'
    else if (r.type === 'a' && e.kind === 'f') e.kind = 'a'
    const sig = r.narg < 0 ? '(…)' : `(${Array.from({ length: r.narg }, (_, i) => `x${i + 1}`).join(', ')})`
    if (!e.signatures.includes(sig)) e.signatures.push(sig)
    map.set(r.name, e)
  }
  write('sqlite-catalog.ts', 'SQLITE_CATALOG', `SQLite ${version}'s pragma_function_list`, [...map.entries()])
}
