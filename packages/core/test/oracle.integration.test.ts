import { afterAll, beforeAll, describe, expect, it } from 'vitest'
import {
  compareSchemas,
  compareTableData,
  createScript,
  dataSyncScript,
  DatabaseService,
  listGrants,
  listPrincipals,
  parseDbml,
  toDbml,
  designId,
  diffTables,
  explainQuery,
  findTable,
  generateMigration,
  getDialect,
  migrationScript,
  toDesignTable,
} from '../src/index.js'

/** Oracle (thin mode, no Instant Client). Requires the `oracle` service from docker-compose.test.yml. */
const skip = (process.env.DBM_SKIP ?? '').split(',').includes('oracle')
const config = { id: 'ora', name: 'ora', driver: 'oracle' as const, host: '127.0.0.1', port: 15219, user: 'shop', password: 'mastermind', database: 'FREEPDB1' }

describe.skipIf(skip)('oracle', () => {
  const svc = new DatabaseService()
  const run = async (sql: string, session?: string) => {
    const [o] = await svc.runScript('ora', sql, { session })
    if (o?.error) throw new Error(`${sql}\n→ ${o.error.message}`)
    return o!
  }

  beforeAll(async () => {
    await svc.connect(config)
    for (const t of ['PAYMENTS', 'ORDERS', 'CUSTOMERS']) await svc.runScript('ora', `DROP TABLE ${t} CASCADE CONSTRAINTS PURGE`)
    await run(`CREATE TABLE customers (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR2(100) NOT NULL, email VARCHAR2(200) UNIQUE, created_at DATE DEFAULT SYSDATE, notes CLOB)`)
    await run(`COMMENT ON TABLE customers IS 'People who buy things'`)
    await run(`CREATE TABLE orders (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id NUMBER NOT NULL REFERENCES customers(id) ON DELETE CASCADE, total NUMBER(12,2) NOT NULL, status VARCHAR2(20))`)
    await run(`CREATE INDEX orders_status_idx ON orders (status)`)
    await svc.runScript(
      'ora',
      `INSERT INTO customers (name, email, notes) VALUES ('Alice', 'alice@example.com', 'gold')\n/\nINSERT INTO customers (name, email) VALUES ('Čeněk 50%_off', NULL)\n/\nBEGIN\n  FOR i IN 1..120 LOOP\n    INSERT INTO orders (customer_id, total, status) VALUES (MOD(i, 2) + 1, i * 10.5, CASE WHEN MOD(i, 2) = 0 THEN 'paid' ELSE 'new' END);\n  END LOOP;\n  COMMIT;\nEND;\n/`,
    )
  }, 120_000)
  afterAll(() => svc.disconnectAll())

  it('introspects tables, keys, comments and types', async () => {
    const snapshot = await svc.schema('ora', true)
    expect(snapshot.defaultSchema).toBe('SHOP')
    const c = findTable(snapshot, { name: 'CUSTOMERS' })!
    expect(c.comment).toBe('People who buy things')
    expect(c.primaryKey).toEqual(['ID'])
    expect(c.columns.find((x) => x.name === 'ID')!.isIdentity).toBe(true)
    expect(c.columns.find((x) => x.name === 'NAME')!.dataType).toBe('VARCHAR2(100)')
    const o = findTable(snapshot, { name: 'ORDERS' })!
    expect(o.foreignKeys[0]).toMatchObject({ columns: ['CUSTOMER_ID'], refTable: 'CUSTOMERS', onDelete: 'CASCADE' })
    expect(o.indexes.map((i) => i.name)).toContain('ORDERS_STATUS_IDX')
  })

  it('runs queries with LOBs, dates and exact numbers as text, truncating at maxRows', async () => {
    const [r] = await svc.runScript('ora', 'SELECT name, notes, created_at, 12345678901234567890 AS big FROM customers ORDER BY id')
    const row = r!.results![0]!.rows[0]!
    expect(row[0]).toBe('Alice')
    expect(row[1]).toBe('gold')
    expect(String(row[2])).toMatch(/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/)
    expect(row[3]).toBe('12345678901234567890')
    const [t] = await svc.runScript('ora', 'SELECT * FROM orders', { maxRows: 10 })
    expect(t!.results![0]!.rows).toHaveLength(10)
    expect(t!.results![0]!.truncated).toBe(true)
  })

  it('filters case-insensitively, sorts and paginates', async () => {
    const page = await svc.fetchTable('ora', {
      table: { schema: 'SHOP', name: 'CUSTOMERS' },
      filter: { kind: 'condition', id: 'x', column: 'NAME', operator: 'contains', value: 'čeněk 50%_' },
      limit: 5,
    })
    expect(page.result.rows).toHaveLength(1)
    const orders = await svc.fetchTable('ora', {
      table: { schema: 'SHOP', name: 'ORDERS' },
      filter: { kind: 'condition', id: 'y', column: 'STATUS', operator: 'eq', value: 'paid' },
      sort: [{ column: 'TOTAL', direction: 'desc' }],
      limit: 3,
      offset: 1,
    })
    expect(orders.result.rows.map((r) => Number(r[2]))).toEqual([1239, 1218, 1197])
    expect(await svc.countTable('ora', { table: { schema: 'SHOP', name: 'ORDERS' } })).toBe(120)
  })

  it('applies grid edits atomically', async () => {
    const table = { schema: 'SHOP', name: 'CUSTOMERS' }
    await svc.applyChanges('ora', table, [{ type: 'insert', values: { NAME: 'Dana', EMAIL: 'dana@example.com' } }])
    await expect(svc.applyChanges('ora', table, [{ type: 'insert', values: { NAME: 'Dup', EMAIL: 'dana@example.com' } }])).rejects.toThrow()
    expect(await svc.applyChanges('ora', table, [{ type: 'delete', key: { EMAIL: 'dana@example.com' } }])).toEqual([1])
  })

  it('auto-commits in editor sessions unless a transaction was started', async () => {
    await run(`UPDATE customers SET name = 'Alicia' WHERE id = 1`, 's1')
    const other = new DatabaseService()
    await other.connect({ ...config, id: 'ora2' })
    const [seen] = await other.runScript('ora2', 'SELECT name FROM customers WHERE id = 1')
    expect(seen!.results![0]!.rows).toEqual([['Alicia']])
    await run('SET TRANSACTION READ WRITE', 's1')
    await run(`UPDATE customers SET name = 'Hidden' WHERE id = 1`, 's1')
    const [still] = await other.runScript('ora2', 'SELECT name FROM customers WHERE id = 1')
    expect(still!.results![0]!.rows).toEqual([['Alicia']])
    await run('ROLLBACK', 's1')
    await run(`UPDATE customers SET name = 'Alice' WHERE id = 1`, 's1')
    await other.disconnectAll()
    await svc.releaseSession('ora', 's1')
  })

  it('cancels long-running statements', async () => {
    const controller = new AbortController()
    setTimeout(() => controller.abort(), 700)
    const started = Date.now()
    // A deliberately huge cross join (seconds to minutes) stands in for a slow report query.
    const [o] = await svc.runScript('ora', 'SELECT COUNT(*) FROM all_objects a, all_objects b, all_objects c', { signal: controller.signal })
    expect(o!.error?.message).toMatch(/cancel/i)
    expect(Date.now() - started).toBeLessThan(10_000)
  })

  it('explains plans', async () => {
    const plan = await explainQuery(svc, 'ora', `SELECT c.name, COUNT(*) FROM orders o JOIN customers c ON c.id = o.customer_id GROUP BY c.name`)
    const flat = JSON.stringify(plan.root)
    expect(flat).toContain('ORDERS')
    expect(flat).toContain('CUSTOMERS')
  })

  it('generates and applies Oracle migrations', async () => {
    const snapshot = await svc.schema('ora', true)
    const draft = toDesignTable(findTable(snapshot, { name: 'CUSTOMERS' })!)
    draft.columns = draft.columns.map((c) => (c.name === 'EMAIL' ? { ...c, name: 'EMAIL_ADDRESS', dataType: 'VARCHAR2(300)' } : c))
    draft.columns.push({ id: designId(), name: 'PHONE', dataType: 'VARCHAR2(40)', nullable: true, comment: 'Mobile' })
    const payments = {
      id: designId(),
      schema: 'SHOP',
      name: 'PAYMENTS',
      columns: [
        { id: designId(), name: 'ID', dataType: 'NUMBER(19)', nullable: false, identity: true },
        { id: designId(), name: 'ORDER_ID', dataType: 'NUMBER', nullable: false },
      ],
      primaryKey: ['ID'],
      foreignKeys: [{ id: designId(), columns: ['ORDER_ID'], refSchema: 'SHOP', refTable: 'ORDERS', refColumns: ['ID'] }],
      indexes: [],
    }
    const migration = generateMigration(diffTables(snapshot.tables, [draft, payments]), getDialect('oracle'), snapshot.tables)
    expect(migration.transactional).toBe(false)
    const outcomes = await svc.runScript('ora', migrationScript(migration, getDialect('oracle')))
    const failed = outcomes.find((o) => o.error)
    expect(failed?.error?.message, failed?.sql).toBeUndefined()
    const after = await svc.schema('ora', true)
    const c = findTable(after, { name: 'CUSTOMERS' })!
    expect(c.columns.map((x) => x.name)).toEqual(expect.arrayContaining(['EMAIL_ADDRESS', 'PHONE']))
    expect(c.columns.find((x) => x.name === 'EMAIL_ADDRESS')!.dataType).toBe('VARCHAR2(300)')
    expect(findTable(after, { name: 'PAYMENTS' })!.foreignKeys[0]!.refTable).toBe('ORDERS')
  })

  it('round-trips the schema through DBML', async () => {
    const snapshot = await svc.schema('ora', true)
    const live = snapshot.tables.filter((t) => t.type === 'table' && ['CUSTOMERS', 'ORDERS'].includes(t.name))
    const model = parseDbml(toDbml(live, { defaultSchema: snapshot.defaultSchema }), { defaultSchema: snapshot.defaultSchema })
    expect(model.errors).toEqual([])
    expect(compareSchemas(model.tables, live, { keepExtra: false })).toEqual([])
  })

  it('compares table data and syncs the differences', async () => {
    await svc.runScript('ora', 'DROP TABLE orders_copy PURGE')
    await run('CREATE TABLE orders_copy AS SELECT * FROM orders')
    await run('DELETE FROM orders_copy WHERE id <= 2')
    await run("UPDATE orders_copy SET status = 'refunded' WHERE id = 10")
    await run('COMMIT')
    const compare = () => compareTableData(svc, { source: { connectionId: 'ora', table: { name: 'ORDERS' } }, target: { connectionId: 'ora', table: { name: 'ORDERS_COPY' } }, keyColumns: ['ID'] })
    const result = await compare()
    expect(result.counts).toEqual({ missing: 2, extra: 0, changed: 1 })
    const outcomes = await svc.runScript('ora', dataSyncScript(result, { name: 'ORDERS_COPY' }, getDialect('oracle')))
    const failed = outcomes.find((o) => o.error)
    expect(failed?.error?.message, failed?.sql).toBeUndefined()
    await run('COMMIT')
    expect((await compare()).counts).toEqual({ missing: 0, extra: 0, changed: 0 })
    await run('DROP TABLE orders_copy PURGE')
  })

  it('lists users and the grants it can see', async () => {
    const principals = await listPrincipals(svc, 'ora')
    expect(principals.map((p) => p.name)).toContain('SHOP')
    await expect(listGrants(svc, 'ora', 'SHOP')).resolves.toBeInstanceOf(Array)
  })

  it('writes a PostgreSQL-flavoured model as Oracle DDL that runs', async () => {
    const { tables } = parseDbml('Table conv_notes {\n  id bigint [pk, increment]\n  done boolean [default: false]\n  body text\n  created timestamptz [default: `now()`]\n}', {})
    await svc.runScript('ora', 'DROP TABLE "conv_notes" PURGE')
    const outcomes = await svc.runScript('ora', createScript(tables, getDialect('oracle'), { translateTypes: true }))
    const failed = outcomes.find((o) => o.error)
    expect(failed?.error?.message, failed?.sql).toBeUndefined()
    await run('DROP TABLE "conv_notes" PURGE')
  })
})
