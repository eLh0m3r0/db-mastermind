import { afterAll, describe, expect, it } from 'vitest'
import { compareSchemas, DatabaseService, generateMigration, getDialect, migrationScript } from '../src/index.js'

const skip = (process.env.DBM_SKIP ?? '').split(',').includes('postgres')

describe.skipIf(skip)('schema compare (postgres)', () => {
  const svc = new DatabaseService()
  afterAll(() => svc.disconnectAll())

  it('migrates the target to match the source, then finds no differences', async () => {
    await svc.connect({ id: 'pg', name: 'pg', driver: 'postgres', host: '127.0.0.1', port: 54329, user: 'postgres', password: 'mastermind', database: 'mastermind' })
    const setup = [
      'DROP SCHEMA IF EXISTS cmp_src CASCADE',
      'DROP SCHEMA IF EXISTS cmp_dst CASCADE',
      'CREATE SCHEMA cmp_src',
      'CREATE SCHEMA cmp_dst',
      'CREATE TABLE cmp_src.customers (id serial PRIMARY KEY, name text NOT NULL, email varchar(200), vip boolean DEFAULT false)',
      'CREATE TABLE cmp_src.orders (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id int NOT NULL REFERENCES cmp_src.customers(id) ON DELETE CASCADE, total numeric(12,2) NOT NULL, status text)',
      'CREATE INDEX ix_src_status ON cmp_src.orders (status)',
      'CREATE TABLE cmp_src.payments (id serial PRIMARY KEY, order_id bigint REFERENCES cmp_src.orders(id))',
      'CREATE TABLE cmp_dst.customers (id serial PRIMARY KEY, name varchar(50) NOT NULL)',
      'CREATE TABLE cmp_dst.orders (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id int NOT NULL, total numeric(12,2) NOT NULL, CONSTRAINT my_custom_fk FOREIGN KEY (customer_id) REFERENCES cmp_dst.customers(id) ON DELETE CASCADE)',
      'CREATE TABLE cmp_dst.legacy (id int)',
    ]
    for (const sql of setup) {
      const [o] = await svc.runScript('pg', sql)
      expect(o!.error, sql).toBeUndefined()
    }
    const snap = await svc.schema('pg', true)
    const src = snap.tables.filter((t) => t.schema === 'cmp_src')
    const dst = snap.tables.filter((t) => t.schema === 'cmp_dst')
    const changes = compareSchemas(src, dst, { keepExtra: true })
    // The differently named but identical foreign key is not touched.
    expect(changes.some((c) => c.kind === 'drop_foreign_key')).toBe(false)
    const script = migrationScript(generateMigration(changes, getDialect('postgres'), dst), getDialect('postgres'))
    const outcomes = await svc.runScript('pg', script)
    const failed = outcomes.find((o) => o.error)
    expect(failed?.error?.message, failed?.sql).toBeUndefined()

    const after = await svc.schema('pg', true)
    const again = compareSchemas(
      after.tables.filter((t) => t.schema === 'cmp_src'),
      after.tables.filter((t) => t.schema === 'cmp_dst'),
      { keepExtra: true },
    )
    expect(again).toEqual([])
    const payments = after.tables.find((t) => t.schema === 'cmp_dst' && t.name === 'payments')!
    expect(payments.foreignKeys[0]).toMatchObject({ refSchema: 'cmp_dst', refTable: 'orders' })
    await svc.runScript('pg', 'DROP SCHEMA cmp_src CASCADE; DROP SCHEMA cmp_dst CASCADE')
  })
})
