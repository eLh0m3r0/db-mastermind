import { describe, expect, it } from 'vitest'
import { compareSchemas, createScript, designId, diffTable, generateMigration, getDialect, impactChecks, liquibaseChangelog, migrationScript, parseDbml, toDesignTable, type TableInfo } from '../src/index.js'

const orders: TableInfo = {
  schema: 'public',
  name: 'orders',
  type: 'table',
  columns: [
    { name: 'id', ordinal: 1, dataType: 'integer', nullable: false, isPrimaryKey: true, isIdentity: true },
    { name: 'status', ordinal: 2, dataType: 'text', nullable: true, isPrimaryKey: false, isIdentity: false },
    { name: 'note', ordinal: 3, dataType: 'varchar(200)', nullable: true, isPrimaryKey: false, isIdentity: false },
  ],
  primaryKey: ['id'],
  foreignKeys: [],
  indexes: [{ name: 'orders_pkey', columns: ['id'], unique: true, primary: true }],
}

describe('schema diff & migration', () => {
  it('produces no changes for an untouched table', () => {
    expect(diffTable(orders, toDesignTable(orders))).toEqual([])
  })

  it('orders renames before alters and warns about risky changes', () => {
    const draft = toDesignTable(orders)
    draft.columns[1] = { ...draft.columns[1]!, nullable: false }
    draft.columns[2] = { ...draft.columns[2]!, name: 'remark', dataType: 'varchar(50)' }
    const changes = diffTable(orders, draft)
    expect(changes.map((c) => c.kind)).toEqual(['rename_column', 'alter_column', 'alter_column'])
    const m = generateMigration(changes, getDialect('postgres'), [orders])
    expect(m.statements).toEqual([
      'ALTER TABLE "public"."orders" RENAME COLUMN "note" TO "remark"',
      'ALTER TABLE "public"."orders" ALTER COLUMN "status" SET NOT NULL',
      'ALTER TABLE "public"."orders" ALTER COLUMN "remark" TYPE varchar(50) USING "remark"::varchar(50)',
    ])
    expect(m.warnings.map((w) => w.level)).toEqual(['warning', 'warning'])
    expect(m.rollback[0]).toContain('TYPE varchar(200)')
    expect(migrationScript(m, getDialect('postgres'))).toMatch(/^-- WARNING[\s\S]*BEGIN;\n[\s\S]*COMMIT;$/)
    expect(impactChecks(changes, getDialect('postgres'))).toEqual([
      { label: 'orders.status: rows with NULL', sql: 'SELECT COUNT(*) FROM "public"."orders" WHERE "status" IS NULL' },
    ])
  })

  it('uses dialect-specific syntax', () => {
    const draft = toDesignTable(orders)
    draft.columns[1] = { ...draft.columns[1]!, name: 'state' }
    draft.columns.push({ id: designId(), name: 'total', dataType: 'decimal(12,2)', nullable: false, defaultValue: '0' })
    const changes = diffTable(orders, draft)
    expect(generateMigration(changes, getDialect('mssql')).statements).toEqual([
      "EXEC sp_rename N'public.orders.status', N'state', 'COLUMN'",
      'ALTER TABLE [public].[orders] ADD [total] decimal(12,2) NOT NULL DEFAULT 0',
    ])
    expect(generateMigration(changes, getDialect('mysql')).statements[1]).toBe('ALTER TABLE `public`.`orders` ADD COLUMN `total` decimal(12,2) NOT NULL DEFAULT 0')
  })

  it('creates tables with keys, foreign keys and indexes', () => {
    const m = generateMigration(
      [
        {
          kind: 'create_table',
          table: {
            id: 'x',
            name: 'payments',
            columns: [
              { id: 'a', name: 'id', dataType: 'bigint', nullable: false, identity: true },
              { id: 'b', name: 'order_id', dataType: 'integer', nullable: false },
            ],
            primaryKey: ['id'],
            foreignKeys: [{ id: 'f', columns: ['order_id'], refTable: 'orders', refColumns: ['id'], onDelete: 'CASCADE' }],
            indexes: [{ id: 'i', columns: ['order_id'], unique: false }],
          },
        },
      ],
      getDialect('postgres'),
    )
    expect(m.statements).toEqual([
      'CREATE TABLE "payments" (\n  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  "order_id" integer NOT NULL,\n  CONSTRAINT "pk_payments_id" PRIMARY KEY ("id")\n)',
      'CREATE INDEX "ix_payments_order_id" ON "payments" ("order_id")',
      'ALTER TABLE "payments" ADD CONSTRAINT "fk_payments_order_id" FOREIGN KEY ("order_id") REFERENCES "orders" ("id") ON DELETE CASCADE',
    ])
    expect(m.rollback).toEqual(['DROP TABLE "payments"'])
  })

  it('does not touch indexes and keys when a column inside them is renamed', () => {
    const withUnique: TableInfo = {
      ...orders,
      indexes: [...orders.indexes, { name: 'orders_note_key', columns: ['note'], unique: true, primary: false, constraint: true }],
    }
    const draft = toDesignTable(withUnique)
    draft.columns[2] = { ...draft.columns[2]!, name: 'remark' }
    // The designer renames the column inside the index too.
    draft.indexes = draft.indexes.map((i) => ({ ...i, columns: ['remark'] }))
    expect(diffTable(withUnique, draft).map((c) => c.kind)).toEqual(['rename_column'])
  })

  it('drops constraint-backed unique indexes with DROP CONSTRAINT', () => {
    const withUnique: TableInfo = {
      ...orders,
      indexes: [...orders.indexes, { name: 'orders_note_key', columns: ['note'], unique: true, primary: false, constraint: true }],
    }
    const draft = toDesignTable(withUnique)
    draft.indexes = []
    expect(generateMigration(diffTable(withUnique, draft), getDialect('postgres')).statements).toEqual([
      'ALTER TABLE "public"."orders" DROP CONSTRAINT "orders_note_key"',
    ])
    expect(generateMigration(diffTable(withUnique, draft), getDialect('mysql')).statements).toEqual(['DROP INDEX `orders_note_key` ON `public`.`orders`'])
  })

  it('flags dropping data as dangerous', () => {
    const draft = toDesignTable(orders)
    draft.dropped = true
    const m = generateMigration(diffTable(orders, draft), getDialect('postgres'))
    expect(m.statements).toEqual(['DROP TABLE "public"."orders"'])
    expect(m.warnings[0]!.level).toBe('danger')
  })
})

describe('compareSchemas', () => {
  it('produces the changes that make the target match the source', async () => {
    const target: TableInfo = { ...orders, columns: orders.columns.slice(0, 2) }
    const extra: TableInfo = { ...orders, name: 'legacy', columns: orders.columns.slice(0, 1), indexes: [] }
    const changes = compareSchemas([orders], [target, extra])
    expect(changes.map((c) => c.kind)).toEqual(['drop_table', 'add_column'])
    expect(compareSchemas([orders], [target, extra], { keepExtra: true }).map((c) => c.kind)).toEqual(['add_column'])
    expect(compareSchemas([orders], [orders])).toEqual([])
  })

  it('creates tables with their check constraints', () => {
    const { tables } = parseDbml("Table products {\n  id int [pk]\n  price numeric(10,2)\n\n  checks {\n    `price >= 0` [name: 'price_not_negative']\n    `price < 1000000`\n  }\n}")
    const sql = createScript(tables, getDialect('postgres'), { translateTypes: true })
    expect(sql).toContain('CONSTRAINT "price_not_negative" CHECK (price >= 0)')
    expect(sql).toContain('  CHECK (price < 1000000)')
    expect(createScript(tables, getDialect('mssql'), { translateTypes: true })).toContain('CONSTRAINT [price_not_negative] CHECK (price >= 0)')
  })

  it('adds the foreign keys of new tables after every table exists', () => {
    // `lines` references `orders`, which the model lists later; `orders` and `people` reference each other.
    const { tables } = parseDbml(
      'Table lines {\n  id int [pk]\n  order_id int [ref: > orders.id]\n}\nTable orders {\n  id int [pk]\n  person_id int [ref: > people.id]\n}\nTable people {\n  id int [pk]\n  last_order int [ref: > orders.id]\n}',
    )
    const migration = generateMigration(compareSchemas(tables, [], { keepExtra: true }), getDialect('postgres'))
    const kinds = migration.statements.map((sql) => /^(CREATE TABLE|ALTER TABLE)/.exec(sql)?.[1])
    expect(kinds).toEqual(['CREATE TABLE', 'CREATE TABLE', 'CREATE TABLE', 'ALTER TABLE', 'ALTER TABLE', 'ALTER TABLE'])
    // The rollback takes the keys between the new tables off before it drops the tables.
    expect(migration.rollback.map((sql) => sql.split(' ').slice(0, 2).join(' '))).toEqual(['ALTER TABLE', 'ALTER TABLE', 'ALTER TABLE', 'DROP TABLE', 'DROP TABLE', 'DROP TABLE'])
  })

  it('gives every constraint and index it names a name of its own', () => {
    const fk = { name: undefined as unknown as string, columns: ['artist_id'], refTable: 'artist', refColumns: ['id'] }
    const alias: TableInfo = {
      name: 'alias',
      type: 'table',
      columns: [
        { name: 'artist_id', ordinal: 1, dataType: 'int', nullable: false, defaultValue: null, isPrimaryKey: false, isIdentity: false },
        { name: 'other_id', ordinal: 2, dataType: 'int', nullable: false, defaultValue: null, isPrimaryKey: false, isIdentity: false },
      ],
      primaryKey: [],
      // The same relationship drawn twice, a second one over the same column, and two indexes on one column.
      foreignKeys: [fk, { ...fk }, { ...fk, refColumns: ['main_id'] }],
      indexes: [
        { name: undefined as unknown as string, columns: ['artist_id'], unique: false, primary: false },
        { name: undefined as unknown as string, columns: ['artist_id'], unique: false, primary: false },
      ],
    }
    const sql = createScript([alias], getDialect('postgres'))
    expect(sql.match(/ADD CONSTRAINT "[^"]+"/g)).toEqual(['ADD CONSTRAINT "fk_alias_artist_id"', 'ADD CONSTRAINT "fk_alias_artist_id_2"'])
    expect(sql.match(/CREATE INDEX "[^"]+"/g)).toEqual(['CREATE INDEX "ix_alias_artist_id"', 'CREATE INDEX "ix_alias_artist_id_2"'])
  })

  it('writes a check for the database: quoted where a bare name would be another column, `value` as the column', () => {
    const { tables } = parseDbml('Table "Player" {\n  id int [pk]\n  "Gender" char(1) [check: `value IS NULL OR value IN (\'M\',\'F\')`]\n  "Age" int\n  low int\n\n  checks {\n    `Age > 0 and low < upper(\'Age\') and length(low) > 0`\n  }\n}')
    const pg = createScript(tables, getDialect('postgres'))
    expect(pg).toContain(`CHECK ("Gender" IS NULL OR "Gender" IN ('M','F'))`)
    expect(pg).toContain(`CHECK ("Age" > 0 and low < upper('Age') and length(low) > 0)`)
    // SQL Server and MySQL find a column whatever its case: only the placeholder is replaced.
    expect(createScript(tables, getDialect('mssql'))).toContain(`CHECK ([Gender] IS NULL OR [Gender] IN ('M','F'))`)
    expect(createScript(tables, getDialect('mysql'))).toContain('CHECK (Age > 0 and low')
  })

  it('sees one type under the names a model and a database give it', () => {
    const column = (name: string, dataType: string, defaultValue: string | null = null, isIdentity = false) => ({ name, ordinal: 1, dataType, nullable: true, defaultValue, isPrimaryKey: false, isIdentity })
    const table = (columns: ReturnType<typeof column>[]): TableInfo => ({ name: 't', type: 'table', columns, primaryKey: [], foreignKeys: [], indexes: [] })
    const model = table([
      column('a', 'VARCHAR(90)', "'new'"),
      column('b', 'char(1)'),
      column('c', 'int', '0'),
      column('d', 'timestamp', 'CURRENT_TIMESTAMP'),
      column('e', 'decimal(10, 2)', '(0)'),
      column('f', 'serial'),
      column('g', 'timestamp with time zone'),
      column('h', 'bool', 'FALSE'),
    ])
    const database = table([
      column('a', 'character varying(90)', "'new'::character varying"),
      column('b', 'character(1)'),
      column('c', 'integer', '0'),
      column('d', 'timestamp without time zone', 'now()'),
      column('e', 'numeric(10,2)', '0'),
      column('f', 'integer', "nextval('t_f_seq'::regclass)", true),
      column('g', 'timestamptz'),
      column('h', 'boolean', 'false'),
    ])
    expect(compareSchemas([model], [database])).toEqual([])
    // Real differences are still differences.
    const changed = compareSchemas([table([column('a', 'varchar(100)', "'NEW'"), column('c', 'bigint', '1')])], [table([column('a', 'character varying(90)', "'new'::character varying"), column('c', 'integer', '0')])], { keepExtra: true })
    expect(changed.map((c) => (c.kind === 'alter_column' ? [c.column, c.changes.type, c.changes.default] : c.kind))).toEqual([['a', true, true], ['c', true, true]])
    // `serial` brings its own sequence: no identity clause on top of it.
    expect(createScript([table([{ ...column('f', 'serial'), isIdentity: true }])], getDialect('postgres'))).toContain('"f" serial\n')
  })

  it('orders a migration so that every statement finds what it needs', () => {
    const column = (name: string, dataType: string, more: Partial<TableInfo['columns'][number]> = {}) => ({ name, ordinal: 1, dataType, nullable: true, defaultValue: null, isPrimaryKey: false, isIdentity: false, ...more })
    const table = (name: string, columns: TableInfo['columns'], more: Partial<TableInfo> = {}): TableInfo => ({ name, type: 'table', columns, primaryKey: [], foreignKeys: [], indexes: [], ...more })
    const fk = (name: string, column: string, refTable: string, refColumn = 'id') => ({ name, columns: [column], refTable, refColumns: [refColumn] })
    const pg = getDialect('postgres')
    const sqlFor = (model: TableInfo[], database: TableInfo[]) => generateMigration(compareSchemas(model, database), pg, database).statements

    // Two tables that reference each other, and one that references them, all leave: keys of the circle first.
    const a = table('a', [column('id', 'int'), column('b_id', 'int')], { foreignKeys: [fk('a_b', 'b_id', 'b')] })
    const b = table('b', [column('id', 'int'), column('a_id', 'int')], { foreignKeys: [fk('b_a', 'a_id', 'a')] })
    const c = table('c', [column('id', 'int'), column('a_id', 'int')], { foreignKeys: [fk('c_a', 'a_id', 'a')] })
    const drops = sqlFor([], [a, b, c])
    expect(drops.map((sql) => sql.replace(/^ALTER TABLE ("\w+") DROP CONSTRAINT.*/, 'cut $1'))).toEqual(['cut "b"', 'DROP TABLE "c"', 'DROP TABLE "a"', 'DROP TABLE "b"'])

    // A new table references a column an existing table only gets in the same migration.
    const parent = table('parent', [column('id', 'int', { nullable: false, isPrimaryKey: true })], { primaryKey: ['id'] })
    const parentWithCode = table('parent', [...parent.columns, column('code', 'int')], { primaryKey: ['id'], indexes: [{ name: 'ux_code', columns: ['code'], unique: true, primary: false }] })
    const child = table('child', [column('code', 'int')], { foreignKeys: [fk('child_parent', 'code', 'parent', 'code')] })
    const grown = sqlFor([parentWithCode, child], [parent])
    expect(grown.findIndex((sql) => sql.includes('ADD COLUMN "code"'))).toBeLessThan(grown.findIndex((sql) => sql.includes('FOREIGN KEY')))
    expect(grown.at(-1)).toContain('FOREIGN KEY ("code") REFERENCES "parent" ("code")')

    // A type change under a default PostgreSQL can't cast: the default steps aside and comes back.
    const flag = table('t', [column('on', 'boolean', { defaultValue: 'false' })])
    expect(sqlFor([table('t', [column('on', 'bigint', { defaultValue: '0' })])], [flag])).toEqual([
      'ALTER TABLE "t" ALTER COLUMN "on" DROP DEFAULT',
      'ALTER TABLE "t" ALTER COLUMN "on" TYPE bigint USING "on"::bigint',
      'ALTER TABLE "t" ALTER COLUMN "on" SET DEFAULT 0',
    ])
    expect(sqlFor([table('t', [column('on', 'text')])], [flag])).toEqual(['ALTER TABLE "t" ALTER COLUMN "on" DROP DEFAULT', 'ALTER TABLE "t" ALTER COLUMN "on" TYPE text USING "on"::text'])

    // A key column that is dropped: the key goes first (SQL Server refuses otherwise), and its lookup may find nothing.
    const keyed = table('k', [column('old_id', 'int', { nullable: false, isPrimaryKey: true }), column('name', 'text')], { primaryKey: ['old_id'] })
    const rekeyed = table('k', [column('name', 'text'), column('new_id', 'int', { nullable: false, isPrimaryKey: true })], { primaryKey: ['new_id'] })
    const moved = sqlFor([rekeyed], [keyed])
    expect(moved.map((sql) => /DROP CONSTRAINT %I|DROP COLUMN|ADD COLUMN|ADD CONSTRAINT/.exec(sql)?.[0])).toEqual(['DROP CONSTRAINT %I', 'DROP COLUMN', 'ADD COLUMN', 'ADD CONSTRAINT'])
    expect(moved[0]).toContain('IF n IS NOT NULL THEN')

    // An index the database keeps for a foreign key stays only while the key does.
    const supported = table('s', [column('id', 'int'), column('p', 'int')], { foreignKeys: [fk('s_p', 'p', 'parent')], indexes: [{ name: 'ix_s_p', columns: ['p'], unique: false, primary: false }] })
    const withKey = table('s', supported.columns, { foreignKeys: [fk('s_p', 'p', 'parent')] })
    expect(sqlFor([parent, withKey], [parent, supported])).toEqual([])
    expect(sqlFor([parent, table('s', supported.columns)], [parent, supported])).toEqual(['ALTER TABLE "s" DROP CONSTRAINT "s_p"', 'DROP INDEX "ix_s_p"'])

    // The same relationship drawn twice in the model is the one foreign key the database has.
    expect(sqlFor([parent, table('s', supported.columns, { foreignKeys: [fk('x', 'p', 'parent'), fk('y', 'p', 'parent')] })], [parent, withKey])).toEqual([])
  })

  it('makes the schemas a model needs and keeps tables of the same name in their own schema', () => {
    const { tables } = parseDbml('Table sales.orders {\n  id int [pk]\n}\nTable audit.orders {\n  id int [pk]\n  at timestamp\n}\nTable public.plain {\n  id int [pk]\n}')
    const pg = createScript(tables, getDialect('postgres'))
    expect(pg).toContain('CREATE SCHEMA IF NOT EXISTS "sales";\nCREATE SCHEMA IF NOT EXISTS "audit";\nCREATE TABLE "sales"."orders"')
    expect(pg).not.toContain('SCHEMA IF NOT EXISTS "public"')
    expect(createScript(tables, getDialect('mssql'))).toContain("IF SCHEMA_ID(N'sales') IS NULL EXEC(N'CREATE SCHEMA [sales]')")
    expect(createScript(tables, getDialect('oracle'))).not.toContain('CREATE SCHEMA')
    // `dbo` and `main` are only there from the start in the databases that call their own schema so.
    const moved = parseDbml('Table dbo.a {\n  id int [pk]\n}\nTable main.b {\n  id int [pk]\n}').tables
    expect(createScript(moved, getDialect('postgres'))).toContain('CREATE SCHEMA IF NOT EXISTS "dbo";\nCREATE SCHEMA IF NOT EXISTS "main";')
    expect(createScript(moved, getDialect('mssql'))).not.toContain("SCHEMA_ID(N'dbo')")
    // A database that has both schemas: each table is compared with its namesake in its own schema.
    const database = structuredClone(tables)
    database[1]!.columns.pop()
    const changes = compareSchemas(tables, database)
    expect(changes.map((c) => [c.kind, c.table.schema])).toEqual([['add_column', 'audit']])
    expect(generateMigration(changes, getDialect('postgres'), database).statements).toEqual(['ALTER TABLE "audit"."orders" ADD COLUMN "at" timestamp'])
    // A table for a schema the database has stays there; elsewhere it goes where the database's tables are.
    const more = parseDbml('Table audit.log {\n  id int [pk]\n}\nTable other.thing {\n  id int [pk]\n}').tables
    expect(compareSchemas([...tables, ...more], tables).map((c) => (c.kind === 'create_table' ? c.table.schema : c.kind))).toEqual(['audit', 'sales'])
  })

  it('says which view stands in the way of a drop', () => {
    const { tables } = parseDbml('Table orders {\n  id int [pk]\n  note text\n  total int\n}\nTable old {\n  id int [pk]\n}')
    const view: TableInfo = { name: 'v_totals', type: 'view', columns: [], primaryKey: [], foreignKeys: [], indexes: [], definition: 'SELECT id, total FROM orders' }
    const next = [{ ...tables[0]!, columns: tables[0]!.columns.filter((c) => c.name !== 'total' && c.name !== 'note') }]
    const { warnings } = generateMigration(compareSchemas(next, tables), getDialect('postgres'), [...tables, view])
    const about = warnings.filter((w) => w.message.startsWith('v_totals')).map((w) => w.message)
    // The view reads orders.total; it does not read orders.note or the table that goes.
    expect(about).toEqual(['v_totals reads orders.total: change or drop the view first, or the database refuses this.'])
  })

  it('writes a migration as a Liquibase changelog with its rollback', () => {
    const { tables } = parseDbml('Table customers {\n  id int [pk]\n  email varchar(120)\n}')
    const draft = toDesignTable(tables[0]!)
    draft.columns.push({ id: designId('c'), name: 'vat_id', dataType: 'varchar(20)', nullable: true })
    const migration = generateMigration(diffTable(tables[0], draft), getDialect('postgres'), tables)
    const changelog = liquibaseChangelog(migration, { id: '20261111 customers', author: 'Jana Nová', comment: 'VAT id\nfor invoices' })
    expect(changelog.split('\n').slice(0, 4)).toEqual(['--liquibase formatted sql', '', '--changeset Jana_Nová:20261111_customers', '--comment: VAT id for invoices'])
    expect(changelog).toContain('ALTER TABLE "customers" ADD COLUMN "vat_id" varchar(20);')
    expect(changelog).toContain('--rollback ALTER TABLE "customers" DROP COLUMN "vat_id";')
    // No BEGIN / COMMIT of our own: Liquibase runs the changeset in its transaction.
    expect(changelog).not.toMatch(/^(BEGIN|COMMIT)/m)
    expect(liquibaseChangelog({ ...migration, transactional: false }, { id: 'x' })).toContain('--changeset dbmastermind:x runInTransaction:false')
  })
})
