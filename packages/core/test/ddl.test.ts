import { describe, expect, it } from 'vitest'
import { designId, diffTable, generateMigration, getDialect, impactChecks, migrationScript, toDesignTable, type TableInfo } from '../src/index.js'

const orders: TableInfo = {
  schema: 'public',
  name: 'orders',
  type: 'table',
  columns: [
    { name: 'id', ordinal: 1, dataType: 'integer', nullable: false, isPrimaryKey: true, isIdentity: true },
    { name: 'status', ordinal: 2, dataType: 'text', nullable: true, isPrimaryKey: false, isIdentity: false },
    { name: 'note', ordinal: 3, dataType: 'varchar(200)', nullable: true, isPrimaryKey: false, isIdentity: false },
  ],
  primaryKey: ['id'],
  foreignKeys: [],
  indexes: [{ name: 'orders_pkey', columns: ['id'], unique: true, primary: true }],
}

describe('schema diff & migration', () => {
  it('produces no changes for an untouched table', () => {
    expect(diffTable(orders, toDesignTable(orders))).toEqual([])
  })

  it('orders renames before alters and warns about risky changes', () => {
    const draft = toDesignTable(orders)
    draft.columns[1] = { ...draft.columns[1]!, nullable: false }
    draft.columns[2] = { ...draft.columns[2]!, name: 'remark', dataType: 'varchar(50)' }
    const changes = diffTable(orders, draft)
    expect(changes.map((c) => c.kind)).toEqual(['rename_column', 'alter_column', 'alter_column'])
    const m = generateMigration(changes, getDialect('postgres'), [orders])
    expect(m.statements).toEqual([
      'ALTER TABLE "public"."orders" RENAME COLUMN "note" TO "remark"',
      'ALTER TABLE "public"."orders" ALTER COLUMN "status" SET NOT NULL',
      'ALTER TABLE "public"."orders" ALTER COLUMN "remark" TYPE varchar(50) USING "remark"::varchar(50)',
    ])
    expect(m.warnings.map((w) => w.level)).toEqual(['warning', 'warning'])
    expect(m.rollback[0]).toContain('TYPE varchar(200)')
    expect(migrationScript(m, getDialect('postgres'))).toMatch(/^-- WARNING[\s\S]*BEGIN;\n[\s\S]*COMMIT;$/)
    expect(impactChecks(changes, getDialect('postgres'))).toEqual([
      { label: 'orders.status: rows with NULL', sql: 'SELECT COUNT(*) FROM "public"."orders" WHERE "status" IS NULL' },
    ])
  })

  it('uses dialect-specific syntax', () => {
    const draft = toDesignTable(orders)
    draft.columns[1] = { ...draft.columns[1]!, name: 'state' }
    draft.columns.push({ id: designId(), name: 'total', dataType: 'decimal(12,2)', nullable: false, defaultValue: '0' })
    const changes = diffTable(orders, draft)
    expect(generateMigration(changes, getDialect('mssql')).statements).toEqual([
      "EXEC sp_rename N'public.orders.status', N'state', 'COLUMN'",
      'ALTER TABLE [public].[orders] ADD [total] decimal(12,2) NOT NULL DEFAULT 0',
    ])
    expect(generateMigration(changes, getDialect('mysql')).statements[1]).toBe('ALTER TABLE `public`.`orders` ADD COLUMN `total` decimal(12,2) NOT NULL DEFAULT 0')
  })

  it('creates tables with keys, foreign keys and indexes', () => {
    const m = generateMigration(
      [
        {
          kind: 'create_table',
          table: {
            id: 'x',
            name: 'payments',
            columns: [
              { id: 'a', name: 'id', dataType: 'bigint', nullable: false, identity: true },
              { id: 'b', name: 'order_id', dataType: 'integer', nullable: false },
            ],
            primaryKey: ['id'],
            foreignKeys: [{ id: 'f', columns: ['order_id'], refTable: 'orders', refColumns: ['id'], onDelete: 'CASCADE' }],
            indexes: [{ id: 'i', columns: ['order_id'], unique: false }],
          },
        },
      ],
      getDialect('postgres'),
    )
    expect(m.statements).toEqual([
      'CREATE TABLE "payments" (\n  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  "order_id" integer NOT NULL,\n  CONSTRAINT "pk_payments_id" PRIMARY KEY ("id")\n)',
      'ALTER TABLE "payments" ADD CONSTRAINT "fk_payments_order_id" FOREIGN KEY ("order_id") REFERENCES "orders" ("id") ON DELETE CASCADE',
      'CREATE INDEX "ix_payments_order_id" ON "payments" ("order_id")',
    ])
    expect(m.rollback).toEqual(['DROP TABLE "payments"'])
  })

  it('does not touch indexes and keys when a column inside them is renamed', () => {
    const withUnique: TableInfo = {
      ...orders,
      indexes: [...orders.indexes, { name: 'orders_note_key', columns: ['note'], unique: true, primary: false, constraint: true }],
    }
    const draft = toDesignTable(withUnique)
    draft.columns[2] = { ...draft.columns[2]!, name: 'remark' }
    // The designer renames the column inside the index too.
    draft.indexes = draft.indexes.map((i) => ({ ...i, columns: ['remark'] }))
    expect(diffTable(withUnique, draft).map((c) => c.kind)).toEqual(['rename_column'])
  })

  it('drops constraint-backed unique indexes with DROP CONSTRAINT', () => {
    const withUnique: TableInfo = {
      ...orders,
      indexes: [...orders.indexes, { name: 'orders_note_key', columns: ['note'], unique: true, primary: false, constraint: true }],
    }
    const draft = toDesignTable(withUnique)
    draft.indexes = []
    expect(generateMigration(diffTable(withUnique, draft), getDialect('postgres')).statements).toEqual([
      'ALTER TABLE "public"."orders" DROP CONSTRAINT "orders_note_key"',
    ])
    expect(generateMigration(diffTable(withUnique, draft), getDialect('mysql')).statements).toEqual(['DROP INDEX `orders_note_key` ON `public`.`orders`'])
  })

  it('flags dropping data as dangerous', () => {
    const draft = toDesignTable(orders)
    draft.dropped = true
    const m = generateMigration(diffTable(orders, draft), getDialect('postgres'))
    expect(m.statements).toEqual(['DROP TABLE "public"."orders"'])
    expect(m.warnings[0]!.level).toBe('danger')
  })
})
